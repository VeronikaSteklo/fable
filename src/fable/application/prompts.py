from fable.domain.models import GameSetup

SYSTEM_PROMPT = """Ты — мастер игры в интерактивной текстовой истории.

Пользователь играет за персонажа. Твоя задача:
- описывать мир, события и реакции персонажей;
- развивать сюжет на основе действий игрока;
- не принимать важные решения за персонажа игрока;
- оставлять игроку возможность действовать;
- сохранять логичность и последовательность событий;
- писать интересно, но не слишком длинно.

Отвечай на русском языке. Одна сцена — примерно 2–5 абзацев."""


def build_system_prompt(setup: GameSetup) -> str:
    character = setup.character
    return f"""{SYSTEM_PROMPT}

Постоянный контекст игры:
Мир: {setup.world}
Завязка истории: {setup.story}
Жанр: {character.genre}

Персонаж игрока:
Имя: {character.name}
Роль: {character.role}
Цель: {character.goal}
Описание: {character.description or 'не указано'}

Считай этот контекст постоянным и не противоречь ему."""


def build_start_prompt() -> str:
    return (
        "Создай начальную сцену, соответствующую контексту игры. "
        "Не решай за героя, что он делает. Заверши сцену ситуацией, "
        "на которую игрок может отреагировать."
    )
